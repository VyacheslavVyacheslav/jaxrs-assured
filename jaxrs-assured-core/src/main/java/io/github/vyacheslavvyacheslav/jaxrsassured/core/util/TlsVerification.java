package io.github.vyacheslavvyacheslav.jaxrsassured.core.util;

/**
 * Проверка TLS-сертификата сервера. По умолчанию включена; выключают явно — для тестовых стендов
 * с самоподписанным сертификатом. Без проверки соединение не защищено от подмены сервера.
 */
public enum TlsVerification {

    /** Сертификат проверяется по доверенным центрам JVM, имя хоста — по сертификату. */
    ENABLED,

    /** Принимается любой сертификат и любое имя хоста. Только для тестовых стендов. */
    DISABLED
}
